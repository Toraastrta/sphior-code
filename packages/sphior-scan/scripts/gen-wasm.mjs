/**
 * gen-wasm.mjs — tree-sitter の WASM を base64 で TS へ埋め込み生成
 *
 * 自己完結配布のため、web-tree-sitter ランタイムと Python 文法の WASM を
 * base64 化して src/gen/wasm-blobs.ts を生成（gitignore）。python-ast がこれを
 * デコードして tree-sitter を init する（実行時のファイル解決を不要にする）。
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const rt = readFileSync(join(root, "node_modules/web-tree-sitter/tree-sitter.wasm")).toString("base64");
const py = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-python.wasm")).toString("base64");
const go = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-go.wasm")).toString("base64");
const php = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-php.wasm")).toString("base64");
const rb = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-ruby.wasm")).toString("base64");
const java = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-java.wasm")).toString("base64");
const cs = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-c_sharp.wasm")).toString("base64");
const rust = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-rust.wasm")).toString("base64");
const kt = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-kotlin.wasm")).toString("base64");
const c = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-c.wasm")).toString("base64");
const cpp = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-cpp.wasm")).toString("base64");
const scala = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-scala.wasm")).toString("base64");
const swift = readFileSync(join(root, "node_modules/tree-sitter-wasms/out/tree-sitter-swift.wasm")).toString("base64");

const outDir = join(root, "src/gen");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "wasm-blobs.ts"),
  `// generated by scripts/gen-wasm.mjs — do not edit\n` +
    `export const TS_RUNTIME_WASM_B64 = ${JSON.stringify(rt)};\n` +
    `export const PY_GRAMMAR_WASM_B64 = ${JSON.stringify(py)};\n` +
    `export const GO_GRAMMAR_WASM_B64 = ${JSON.stringify(go)};\n` +
    `export const PHP_GRAMMAR_WASM_B64 = ${JSON.stringify(php)};\n` +
    `export const RB_GRAMMAR_WASM_B64 = ${JSON.stringify(rb)};\n` +
    `export const JAVA_GRAMMAR_WASM_B64 = ${JSON.stringify(java)};\n` +
    `export const CS_GRAMMAR_WASM_B64 = ${JSON.stringify(cs)};\n` +
    `export const RUST_GRAMMAR_WASM_B64 = ${JSON.stringify(rust)};\n` +
    `export const KT_GRAMMAR_WASM_B64 = ${JSON.stringify(kt)};\n` +
    `export const C_GRAMMAR_WASM_B64 = ${JSON.stringify(c)};\n` +
    `export const CPP_GRAMMAR_WASM_B64 = ${JSON.stringify(cpp)};\n` +
    `export const SCALA_GRAMMAR_WASM_B64 = ${JSON.stringify(scala)};\n` +
    `export const SWIFT_GRAMMAR_WASM_B64 = ${JSON.stringify(swift)};\n`,
);

console.log(`[sphior-scan] wasm blobs generated (${13} langs)`);
