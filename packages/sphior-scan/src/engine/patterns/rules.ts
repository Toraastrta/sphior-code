import type { Confidence, Severity } from "../types";

export interface PatternRule {
  id: string;
  cwe: string;
  owasp: string;
  severity: Severity;
  title: string;
  message: string;
  remediation: string;
  /** 対象拡張子（小文字・ドットなし）。 */
  exts: string[];
  pattern: RegExp; // global で使用
  references?: string[];
  /**
   * 既定 confidence の上書き（省略時 "likely"）。
   * 実世界で非セキュリティ用途と両義になりうるパターン（例: java.util.Random は
   * 乱択・ジッタ等の正当用途もある）は "needs_review" にし、レポートでは Tail に隔離して
   * overclaim を避ける（disposition 思想と整合）。
   */
  confidence?: Confidence;
}

